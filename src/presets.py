# `SYSTEM_PROMPT` и не вариант промпта фактов (§3.3): другая задача — не вести
# выжимку разговора, а разложить сказанное игроком по закрытой карте ключей.
#
# Слова «слой» модели знать не нужно: список ключей сгруппирован по двум
# вопросам — «что верно только для этой партии» и «что верно для игрока
# вообще». Сомнение решается в сторону партии: ошибка в рабочей памяти уйдёт
