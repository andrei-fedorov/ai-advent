# `FACTS_PROMPT`): поправка — новое значение ключа, а не «удалить»; молчание
# не значит отмену; значение пишется целиком; ключ без содержания не
# заводится; выводы ассистента в значение не дописываются; образец формата —
# голой строкой. Сверх них — `знания о правилах` только со слов игрока и «не
