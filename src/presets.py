# --- Стратегии управления контекстом (день 9) ----------------------------
# Параметры стратегии «Сводка + последние N» — константы модуля, а не элементы
# интерфейса: крутилки увели бы день в подбор чисел (спецификация дня 9, §12).
# В дебаг-панели они видны словами, через `StrategyState.description`.

# «Последние N как есть» из задания. Число чётное: стек агента растёт парами
# «вопрос + ответ», и срез из чётного числа сообщений всегда начинается с
# `user` — половинок ходов в запросе не бывает.
SUMMARY_KEEP_LAST = 6

# «Каждые 10 сообщений» в задании — пример, а не требование. Шесть выбрано по
# демонстрации: первая свёртка наступает на 12 сообщениях (6 ходов), дальше
# каждые 3 хода — за один прогон видно и первую свёртку, и обновление сводки.
SUMMARY_FOLD_EVERY = 6

# Потолок служебного вызова — страховка, а не рабочая длина: длину сводки
# держит просьба в промпте (`SUMMARY_WORDS`). Он же — потолок роста самой
# сводки: сводка это тоже контекст, и у неё тоже есть бюджет.
#
# ЗАМЕР (спецификация дня 9, §3.1): 13.09.2026, `deepseek-flash`, живой диалог
# из 24 сообщений, три свёртки подряд — на 12, 18 и 24 сообщениях. С лимитом
# «8 предложений» сводки вышли на 256 / 512 / 488 токенов; прежний потолок 400
# оборвал бы вторую на полуслове. С промптом ниже и лимитом «150 слов» —
# 277 / 333 / 330, все `finish_reason=stop`. 800 — запас ≈1.6× над худшим
# замером: упор в потолок остаётся исключением, которое агент логирует.
SUMMARY_MAX_TOKENS = 800

# Рабочее ограничение длины, в самом промпте: `max_tokens` обрывает ответ на
# полуслове, а просьба в промпте даёт законченный текст. Считается в словах, а
# не в предложениях: число предложений модель соблюдает, но растягивает каждое
# (6 предложений — 512 токенов). 150 слов русского текста — ≈300-350 токенов.
SUMMARY_WORDS = 150

# Промпт свёртки — отдельный системный промпт, а не наследник `SYSTEM_PROMPT`:
# свёртка не ответ игроку, а служебная операция, и роль «ассистент по
# правилам» тут только мешала бы (модель начинала бы отвечать на последний
# вопрос вместо того, чтобы сворачивать диалог).
#
# Список «что обязательно сохранить» — это и есть ответ на вопрос, ради
# которого день затевался: к тридцатому вопросу от пятого хода нужны не
# формулировки правил, а несколько фактов о партии и выводы разговора. Выводы
# обязательны (§3.2): книги правил у модели нет до недели 5, Too Many Bones она
# знает плохо, и поправка игрока — ровно то, чего в её весах нет. Сводка
# «разобрали отравление» без вывода вернула бы модель к её исходной ошибке.
#
# Два шаблона — «разобрали <тему>: <к чему пришли>» и «потом отвлеклись на
# <тему>» — подобраны на том же замере: без первого модель теряла, что
# именно сказал игрок, без второго раздувала сводку пересказом разговоров не
# про игру. Меняешь формулировки — прогони несколько свёрток подряд на живом
# диалоге: длина и потери видны только на второй-третьей.
SUMMARY_PROMPT = f"""\
Ты ведёшь краткую сводку разговора между игроком и ассистентом по правилам
настольных игр. Это служебная задача: отвечать на вопросы игрока и объяснять
правила сейчас не нужно.

Тебе дают предыдущую сводку (если она есть) и следующие за ней сообщения
диалога. Верни ОДНУ обновлённую сводку, которая покрывает и предыдущую
сводку, и новые сообщения, — так, чтобы по ней можно было продолжить диалог,
не видя исходных сообщений.

Обязательно сохрани всё из этого, что было в диалоге:
- о какой игре и каких дополнениях идёт речь;
- состав партии: герои, число игроков, сложность;
- какие правила уже разобрали и к какому выводу пришли — одной фразой на
  тему. Если игрок поправлял ассистента, сохрани, что именно сказал игрок;
  если ассистент признал, что не уверен, — в чём именно. Книги правил у
  ассистента нет, и такие выводы ему больше неоткуда взять;
- договорённости и решения игрока: как условились играть спорные места,
  какие режимы и материалы используют, а какие нет;
- открытые вопросы, на которые ответа ещё нет.

Правила:
- формулировки правил целиком не пересказывай: нужны тема и вывод, а не
  списки фаз, шагов, условий и исключений — даже если они занимали
  полдиалога. Форма «разобрали <тему>: <к чему пришли>» — этого достаточно;
- всё, что не относится к игре, сворачивай до одной фразы вида «потом
  отвлеклись на <тему>» — без перечисления того, что там разбирали;
- ничего не выдумывай: в сводке только то, что было в диалоге;
- не пиши вступлений, заголовков и списков;
- пиши по-русски, сплошным текстом, не длиннее {SUMMARY_WORDS} слов. Если не
  помещается, сокращай то, что уже неважно, но не выводы и не договорённости.
"""

# Реестр стратегий: имя → описание для выпадающего списка. Имя совпадает с
# `ContextStrategy.name`, чтобы в логах, в панели и в файле сессии было видно
# ровно то, что выбрано в интерфейсе, — тот же приём, что с пресетами.
#
# Сами экземпляры раздаёт `make_strategies()`, а не этот словарь: память
# сводки относится к конкретному диалогу, поэтому у каждого агента стратегии
# свои (спецификация дня 9, §6.1).
SUMMARY_STRATEGY = "Сводка + последние N"

STRATEGIES: dict[str, str] = {
    context.FULL_HISTORY_NAME: (
        "дни 6-8 — весь стек уходит в модель, запрос растёт с каждым ходом"
    ),
    SUMMARY_STRATEGY: (
        f"день 9 — последние {SUMMARY_KEEP_LAST} сообщений как есть, "
        f"остальное сворачивается в сводку каждые {SUMMARY_FOLD_EVERY} сообщений"
    ),
}

# Стратегия по умолчанию для новых агентов — «Вся история»: день 9 показывает
# «было → стало», и начинать надо с «было». У восстановленных агентов
# умолчания нет, там берётся записанное в файле сессии.
DEFAULT_STRATEGY = context.FULL_HISTORY_NAME


def make_strategies() -> dict[str, "context.ContextStrategy"]:
    """Свежий набор стратегий для одного агента.

    Фабрика, а не готовый словарь: у «Сводки» есть память, и она относится к
    конкретному диалогу. Общий на всех экземпляр означал бы, что сводка одного
    агента уезжает в запрос другого.
    """
    return {
        context.FULL_HISTORY_NAME: context.FullHistory(),
        SUMMARY_STRATEGY: context.SummaryStrategy(
            name=SUMMARY_STRATEGY,
            prompt=SUMMARY_PROMPT,
            keep_last=SUMMARY_KEEP_LAST,
            fold_every=SUMMARY_FOLD_EVERY,
            max_tokens=SUMMARY_MAX_TOKENS,
        ),
    }
