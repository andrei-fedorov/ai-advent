#   переделать план, а просит обойтись без него. Теперь в правиле «вернуться к
#   плану» это сказано прямо, а такая просьба — «нет» со сходом;
# - «план утверждён» без пунктов не бывает: на Р2 («План подходит, поехали.»
#   после двух отказов П1-П2) последний обмен уже не содержал плана, и трекер
