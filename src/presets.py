def _memory_keys(layer: str) -> str:
    """Ключи одной части карты для промпта разбора — «- ключ — описание», в
    порядке карты. Промпт собирается из `MEMORY_MAP`, а не пишется второй раз
    руками: карта и промпт не должны разъехаться (§3.3)."""
    return "\n".join(
        f"- {slot.key} — {slot.description}"
        for slot in MEMORY_MAP
        if slot.layer == layer
    )


