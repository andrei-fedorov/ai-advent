def make_invariants() -> invariants.InvariantBook:
    """Свежая книга инвариантов на одного агента.

    Фабрика, а не общий экземпляр, по той же причине, что `make_memory()`,
    `make_router()` и `make_task_machine()`: сессионные инварианты относятся к
    конкретной сессии. Список событий и режимов автомата приходит из
    `task_state` — у строки режима ровно одно определение на проект.
    """
    return invariants.InvariantBook(
        prompt=GUARD_PROMPT,
        max_tokens=GUARD_MAX_TOKENS,
        text_words=INVARIANT_TEXT_WORDS,
        max_items=INVARIANT_MAX_ITEMS,
        events=task_state.EVENTS,
        modes=task_state.GUARD_MODES,
    )


# Книга и инварианты по умолчанию проверяются при импорте модуля, как карта
# памяти, профиль по умолчанию и автомат: ошибка видна до первого вопроса.
make_invariants()
_default_errors = invariants.validate(
    DEFAULT_INVARIANTS, INVARIANT_TEXT_WORDS, INVARIANT_MAX_ITEMS,
    task_state.EVENTS, task_state.GUARD_MODES,
)
if _default_errors:
    raise ValueError(
        "инварианты по умолчанию: " + "; ".join(_default_errors)
    )
del _default_errors


