def make_strategies() -> dict[str, "context.ContextStrategy"]:
    """Свежий набор стратегий для одного агента.

    Фабрика, а не готовый словарь: у «Сводки» и «Фактов» есть память, и она
    относится к конкретному диалогу. Общий на всех экземпляр означал бы, что
    память одного агента уезжает в запрос другого.
    """
    return {
        context.FULL_HISTORY_NAME: context.FullHistory(),
        SUMMARY_STRATEGY: context.SummaryStrategy(
            name=SUMMARY_STRATEGY,
            prompt=SUMMARY_PROMPT,
            keep_last=SUMMARY_KEEP_LAST,
            fold_every=SUMMARY_FOLD_EVERY,
            max_tokens=SUMMARY_MAX_TOKENS,
        ),
        WINDOW_STRATEGY: context.SlidingWindow(
            name=WINDOW_STRATEGY,
            keep_last=WINDOW_KEEP_LAST,
        ),
        FACTS_STRATEGY: context.StickyFacts(
            name=FACTS_STRATEGY,
            prompt=FACTS_PROMPT,
            keep_last=FACTS_KEEP_LAST,
            max_tokens=FACTS_MAX_TOKENS,
        ),
    }


