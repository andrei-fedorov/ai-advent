# - «вернуться к плану» отличается от «вернуться к шагу» одной фразой с
#   примерами обоих; «переоткрыть» в промпте не упоминается — это кнопка
#   человека;
# - сход с маршрута — необязательная пара строк «сход»/«чем»: ставится, когда
#   пользователь ПРОСИТ обойти этапы, а вопрос про порядок работы сходом не
#   является; сомневаешься — строку не пиши.
#
# Правила, добавленные по сбоям живого прогона §9 (20.09.2026, `deepseek-flash`):
# - «вернуться к плану» — не «давай без плана»: на П1 («Давай без плана — я уже
#   начал раскладывать…») трекер назвал «вернуться к плану» — отказ формально
