# TooManyRules — сущность агента (день 6, неделя 2; день 8 — работа с токенами,
# день 9 — управление контекстом, день 10 — общий служебный вызов, checkpoint'ы
# и ветки диалога; день 11 — модель памяти: рабочая и долговременная память;
# день 12 — профиль пользователя и роутер режима; день 13 — состояние задачи;
# день 14 — инварианты; день 17 — инструменты MCP; день 18 — группа серверов;
# день 19 — сэмплинг: сервер просит модель у клиента).
#
# Единственное место в проекте, где происходят вызовы LLM API. Модуль
# намеренно ничего не знает ни про Gradio, ни про Too Many Bones: внутри
# только конфиг, стек сообщений, вызов API, замер времени, подсчёт токенов
# и стоимости, логирование и обработка ошибок. Наружу агент отдаёт результат
# (`AgentReply`) и своё состояние для дебага (`debug_state`).
#
# Направление зависимостей одностороннее: app.py → presets.py → agent.py →
# tokens.py, context.py, memory.py → context.py, user_profile.py → context.py.
# Из проекта здесь импортируются листья графа, которые сами не импортируют
# ничего, — `tokens.py` (день 8) и `context.py` (день 9), — и `memory.py`
# (день 11) с `user_profile.py` (день 12), которые оба зависят только от
# листа `context.py`; замороженный `app_week1.py` не импортируется
# по-прежнему — см. `docs/TooManyRules — Неделя 2 архитектура.md`, §3, и
# спецификации дня 8, §4, дня 9, §4, дня 10, §5, дня 11, §5, и дня 12, §5.
#
# С дня 9 вызовов LLM API здесь два места: основной вызов (ответ игроку) и
# служебный. До дня 10 служебный был «свёрткой», с дня 10 обслуживает любую
# стратегию с памятью (сводку и факты) одним путём, с дня 11 — ещё и разбор
# памяти, а с дня 12 — ещё и роутер профиля: три работы. Поэтому сам вызов
# вынесен в `_call_service_model()`, а работы вокруг него —
# `_run_context_task()`, `_run_memory_task()` и `_run_route_task()`. Правило
# «вызовы LLM API — только в `agent.py`, в двух местах» остаётся буквальным.
#
# День 10 также добавляет операцию над самой историей — checkpoint и ветку:
# агент фиксирует точку диалога вместе со снимком памяти стратегий и порождает
# от неё нового агента с общим началом истории. Это не стратегия и не вызов
# API — обычная работа со стеком сообщений и с реестром агентов.
#
# День 11 разводит память агента по времени жизни на три слоя (спецификация
# дня 11, §2.1): краткосрочная — разговор (стек и память стратегий, как на
# днях 6-10), рабочая — данные текущей задачи (живёт в файле сессии, в
# `context.working`), долговременная — пользователь вообще (отдельный файл,
# один на процесс). Модель памяти (`memory.AgentMemory`) и хранилище
# долговременной памяти — ещё две необязательные зависимости агента: без них
# агент ведёт себя ровно как на дне 10. Что куда пишется, решает карта памяти,
# а в долговременную память — только человек: разбор предлагает кандидатов,
# сохраняет их `accept_candidates()`.
#
# День 12 добавляет профиль пользователя — не слой памяти и не пресет
# (спецификация дня 12, §2.1), а явные настройки, которые пользователь пишет
# сам. Хранилище профиля (`ProfileStore`) одно на процесс, как долговременная
# память; выбор режима на этот ход (`user_profile.ModeRouter`) — свой у
# каждого агента, как модель памяти. Обе зависимости снова необязательные:
# без них агент ведёт себя ровно как на дне 11. Роутер — третья служебная
# работа вокруг `_call_service_model()`; блок профиля встаёт в запрос сразу
# за системным промптом, перед слоями памяти.
#
# День 13 добавляет состояние задачи — конечный автомат (`task_state.TaskMachine`),
# ещё одна необязательная зависимость: без неё агент ведёт себя ровно как на
# дне 12. Трекер — четвёртая служебная работа вокруг `_call_service_model()`,
# идёт после роутера и перед сборкой запроса; блок состояния задачи встаёт
# сразу за рабочей памятью, перед памятью стратегии. Задачу начинает и
# отменяет только человек — кнопками (`start_task()`, `task_event()`); этап и
# шаг меняет только таблица переходов в `task_state.py`, агент лишь применяет
# её решения и сохраняет их.
#
# День 14 добавляет инварианты — ограничения, которые ассистент не вправе
# нарушить (`invariants.InvariantBook`, спецификация дня 14): ещё две
# необязательные зависимости — книга (своя у каждого агента) и хранилище
# постоянных инвариантов (одно на процесс, `InvariantStore`); без них агент
# ведёт себя ровно как на дне 13. Страж — пятая служебная работа вокруг
# `_call_service_model()`: идёт первым после вызова стратегии, только называет
# конфликт нового сообщения с инвариантами и ход не отменяет. Блок инвариантов
# встаёт первым из блоков агента — сразу за системным промптом, перед
# профилем; инварианты над переходами агент превращает в ограничения автомата
# (`_transition_guards()`) — это единственное место, где книга и автомат
# встречаются. Инварианты пишет только человек: агент их не создаёт и не
# правит, только читает и применяет.
#
# Фаз подготовки в `ask()` теперь шесть: снимок долговременной памяти,
# профиля и инвариантов на ход, служебный вызов стратегии, страж, разбор
# памяти, роутер, трекер — и сборка запроса с блоками инвариантов, профиля,
# слоёв и задачи (порядок блоков — от устойчивого к изменчивому).
#
# День 17 (неделя 4) даёт агенту инструменты — function calling DeepSeek
# поверх MCP-сервера (спецификация дня 17, §5). Инструменты — ещё одна
# необязательная зависимость (`ToolBox`, реализация — `mcp_client.McpToolBox`,
# одна на процесс): без неё агент ведёт себя ровно как на дне 16. Про MCP
# агент не знает — протокол `ToolBox` отдаёт каталог и вызывает инструмент
# словарями. После всех служебных работ `ask()` запрашивает каталог, и
# основной запрос хода становится циклом раундов: модель → вызовы
# инструментов → модель, пока модель не ответит текстом. Раунды — не
# служебные работы, а части основного запроса: каждый считается вызовом API,
# в историю идут только вопрос и финальный ответ. Вызовов LLM API в модуле
# по-прежнему два места: основной (теперь в цикле) и служебный.
#
# День 18 агента почти не трогает: `ToolBox` теперь — группа серверов
# (`mcp_client.McpToolBoxGroup`: FAQ по stdio и сторож FAQ по HTTP), и её
# каталог может прийти не целиком — с необязательным ключом `"warning"`. Он
# дописывается к заметке каталога хода и уходит в лог; остальное — как на
# дне 17.
#
# День 19 добавляет сэмплинг — шестую служебную работу (спецификация дня 19,
# §6.2), и единственную, что идёт не до основного запроса, а внутри него,
# между раундами: сервер, вызванный инструментом, просит модель у клиента, а
# клиент — это агент. Протокол `ToolBox.call()` получает необязательный
# параметр `sample` — обычную функцию над словарями (`agent.py` про MCP
# по-прежнему не знает); агент передаёт её в каждый вызов инструмента, решает
# сервер, пользоваться ли ей. Сэмплинг зовёт тот же `_call_service_model()`,
# что и остальные пять работ, со своими счётчиками `sampling_*`, и не берёт
# замок агента — он выполняется в чужом потоке (`anyio.to_thread` на стороне
# `mcp_client`), пока `ask()` ждёт ответа `_tools.call()` под своим замком.

