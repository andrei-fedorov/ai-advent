    def debug_state(self) -> dict:
        """Состояние агента для дебаг-панели: конфиг, стек, метрики
        последнего вызова, накопленное за время жизни и счётчики процесса."""
        # Один снимок долговременной памяти на рендер (день 11): и в бюджет,
        # и в ключ `long_term` ниже — чтобы «что уходит» и «что лежит» не
        # разъехались между двумя чтениями. Это копия словаря из памяти
        # процесса, файл при этом не читается.
        long_term = self._long_term_entries()
        # Снимок профиля на рендер (день 12) — тем же приёмом: и в бюджет
        # (через `_context_view`), и в ключ `profile` ниже.
        profile = self._profile_snapshot()
        preview = self._preview_mode_choice(profile)
        # Снимок постоянных инвариантов на рендер (день 14) — тем же приёмом:
        # и в бюджет, и в ключ `invariants` ниже.
        always = self._invariant_snapshot()
        view = self._context_view("", long_term, profile, preview, always)[1]
        return {
            "number": self._number,
            "config": asdict(self._config),
            "session_id": self._session_id,
            # С дня 7 здесь имя класса хранилища (`JsonHistoryStore`); None
            # означает агента, живущего только в памяти процесса.
            "store": type(self._store).__name__ if self._store else None,
            "restored_messages": self._restored_messages,
            "store_error": self._store_error,
            "history_size": len(self._messages),
            "messages": self.history,
            "last_call": asdict(self._last_reply) if self._last_reply else None,
            "totals": dict(self._totals),
            "process": process_stats(),
            # Ключи дня 8 — в конце: существующие не переименовываются и не
            # переставляются, иначе поехали бы рендеры дебаг-панели.
            # `context` заполняется из того же `ContextView`, что и ключ
            # `context_view` ниже: бюджет за один рендер считается один раз.
            "context": asdict(view.usage),
            "turns": [asdict(turn) for turn in self._turns],
            "calibration": self.calibration,
            # Ключи дня 9 — тоже в конце. В `context_view` уходит описание
            # назревшей свёртки, а не сама `ContextTask`: её `messages` могут
            # весить сотни килобайт, и в панель им не место.
            "strategy": self._strategy_name,
            "context_view": asdict(view),
            # Ключи дня 10 — в конце. Снимок памяти в `checkpoints` панели не
            # нужен (весит килобайты) и не отдаётся — только id, длина,
            # стратегия и время.
            "checkpoints": [
                {
                    "id": cp.id,
                    "messages": cp.messages,
                    "strategy": cp.strategy,
                    "created_at": cp.created_at,
                }
                for cp in self._checkpoints
            ],
            "branch": asdict(self._branch) if self._branch is not None else None,
            # Ключи дня 11 — в конце. `memory` — рабочая память, кандидаты и
            # последний разбор; `long_term` — путь и тот же снимок записей,
            # по которому посчитан бюджет выше. `None` — модели памяти или
            # долговременной памяти у агента нет.
            "memory": (
                asdict(self._memory.describe(self._messages))
                if self._memory is not None
                else None
            ),
            "request_layers": list(self._request_layers),
            "long_term": (
                {"path": self._long_term.path, "entries": long_term}
                if self._long_term is not None
                else None
            ),
            # Ключи дня 12 — в конце. `None` — профиля у агента нет. `choices`
            # и `preview` — тем же снимком, по которому посчитан бюджет выше;
            # `last` — что реально ушло в запрос прошлого хода (`None` —
            # ходов ещё не было).
            "profile": (
                {
                    "path": self._profile.path,
                    "choice": (
                        self._router.choice
                        if self._router is not None
                        else user_profile.CHOICE_AUTO
                    ),
                    "choices": (
                        self._router.choices(profile)
                        if self._router is not None
                        else [
                            user_profile.CHOICE_AUTO,
                            *(mode.name for mode in profile.modes),
                            user_profile.CHOICE_OFF,
                        ]
                    ),
                    "preview": asdict(preview),
                    "last": (
                        asdict(self._router.last)
                        if self._router is not None and self._router.last is not None
                        else None
                    ),
                    "data": user_profile.dump_profile(profile),
                }
                if self._profile is not None
                else None
            ),
            # Ключ дня 13 — в конце. `None` — автомата у агента нет.
            "task": (
                {
                    "in_request": self._task_in_request,
                    "view": asdict(self._task.describe(self._messages)),
                }
                if self._task is not None
                else None
            ),
            # Ключ дня 14 — в конце. `None` — книги у агента нет.
            "invariants": (
                {
                    "in_request": self._invariants_in_request,
                    "view": asdict(
                        self._invariants.describe(always, self._messages)
                    ),
                    "path": (
                        self._invariant_store.path
                        if self._invariant_store is not None
                        else None
                    ),
                }
                if self._invariants is not None
                else None
            ),
            # Ключ дня 17 — в конце. `None` — инструментов у агента нет.
            # Записи последнего хода (раунды, вызовы, заметка о каталоге)
            # лежат в `last_call` — это поля ответа; здесь — положение
            # переключателя и инструменты последнего полученного каталога.
            "tools": (
                {
                    "name": self._tools.name,
                    "in_request": self._tools_in_request,
                    "catalog": [
                        spec["function"]["name"] for spec in self._last_tool_specs
                    ],
                    "max_rounds": self._tool_max_rounds,
                    "result_max_chars": self._tool_result_max_chars,
                }
                if self._tools is not None
                else None
            ),
        }

    # --- Внутреннее ------------------------------------------------------

    def _build_messages(
        self,
        user_message: str,
        long_term: dict | None = None,
        profile: "user_profile.UserProfile | None" = None,
        mode_choice: "user_profile.ModeChoice | None" = None,
        always: list[dict] | None = None,
    ) -> list[dict]:
        """Единственное место, где собирается список сообщений для запроса.

        С дня 9 сборку делает стратегия: агент отдаёт ей системный промпт,
        весь стек и новый вопрос, а что из этого уедет в модель — решает она
        (`context.py`, §4). Сам стек при этом не меняется: сжимается запрос,
        а не память. День 10 добавил сюда «Скользящее окно» и «Факты +
        последние N», не тронув ни строчки в этом методе — обе встают в тот
        же протокол `ContextStrategy`. Ветки — операция над самой историей
        (`fork()`), а не способ собрать запрос, и этого метода не касаются.

        День 11 дописывает сюда слои памяти (§5.4): поверх того, что вернула
        стратегия, `_with_layers()` вставляет блоки долговременной и рабочей
        памяти. Стратегии о слоях не знают. `long_term` — снимок записей
        долговременной памяти этого хода; `None` — взять свежий.

        День 12 дописывает блок профиля (§5.4): `_with_profile()` вставляет
        его после `_with_layers()`, но целится в то же место — сразу после
        системного промпта, поэтому в итоге он оказывается перед слоями
        (порядок блоков — §2.4). `profile`/`mode_choice` — снимок и решение
        этого хода; `None` — взять свежие (панель).

        День 13 дописывает блок состояния задачи (§5.5): `_with_task()`
        вызывается первым — до слоёв и профиля, — поэтому в итоге он
        оказывается последним из трёх, сразу за рабочей памятью и перед
        памятью стратегии: порядок вызовов обратен порядку блоков.

        День 14 дописывает блок инвариантов (§6.5): `_with_invariants()`
        вызывается последним — после задачи, слоёв и профиля, — поэтому в
        итоге он оказывается первым из блоков, сразу за системным промптом:
        инвариант устойчивее всего остального и старше всего остального.
        `always` — снимок постоянных инвариантов этого хода; `None` — взять
        свежий (панель).
        """
        if long_term is None:
            long_term = self._long_term_entries()
        if profile is None:
            profile = self._profile_snapshot()
        if mode_choice is None:
            mode_choice = self._preview_mode_choice(profile)
        if always is None:
            always = self._invariant_snapshot()
        messages = self.strategy.build(
            self._config.system_prompt, self._messages, user_message
        )
        messages = self._with_task(messages)
        messages = self._with_layers(messages, long_term)
        messages = self._with_profile(messages, profile, mode_choice)
        return self._with_invariants(messages, always)

    def _with_invariants(self, messages: list[dict], always: list[dict]) -> list[dict]:
        """Блок инвариантов в готовом списке сообщений — единственное место,
        где он туда попадает (спецификация дня 14, §6.5). Уходит только если
        блок не `None` (действующих инвариантов нет) и переключатель
        «Инварианты в запросе» включён — выключенный убирает весь блок,
        включая строку конфликта. Встаёт сразу после системного промпта;
        стратегии, модель памяти, профиль и автомат о блоке не знают."""
        if self._invariants is None or not self._invariants_in_request or not messages:
            return messages
        block = self._invariants.block(always, self._messages)
        if block is None:
            return messages
        return messages[:1] + [block] + messages[1:]

    def _invariant_snapshot(self) -> list[dict]:
        """Снимок постоянных инвариантов на ход (день 14, §6.2) — копия
        списка из памяти процесса (файл хранилище читает один раз, при
        создании); `[]` — хранилища или книги нет: без книги читать
        постоянные инварианты некому."""
        if self._invariants is None or self._invariant_store is None:
            return []
        return self._invariant_store.current()

    def _transition_guards(
        self, always: list[dict]
    ) -> tuple["task_state.TransitionGuard", ...]:
        """Единственное место, где инварианты превращаются в ограничения
        автомата (день 14, §6.4): книга про автомат не знает, автомат про
        инварианты не знает — связывает их агент, как на дне 13 он связывает
        хранилище и модель памяти. Книги нет — пустой кортеж, и автомат
        ведёт себя как на дне 13."""
        if self._invariants is None:
            return ()
        return tuple(
            task_state.TransitionGuard(
                event=inv.event, mode=inv.mode, reason=inv.text,
                source_note=f"инвариант {inv.id}",
            )
            for inv in self._invariants.transition_invariants(always)
        )

    def _with_task(self, messages: list[dict]) -> list[dict]:
        """Блок состояния задачи в готовом списке сообщений — единственное
        место, где он туда попадает (спецификация дня 13, §5.5). Уходит
        только если блок не `None` (задачи нет, или она на конечном этапе и
        переход не свежий — решает `TaskMachine.block()`) и переключатель
        «Состояние задачи в запросе» включён. Стратегии, модель памяти и
        профиль о задаче не знают."""
        if self._task is None or not self._task_in_request or not messages:
            return messages
        block = self._task.block(self._messages)
        if block is None:
            return messages
        return messages[:1] + [block] + messages[1:]

    def _with_layers(self, messages: list[dict], long_term: dict) -> list[dict]:
        """Блоки слоёв памяти в готовом списке сообщений — единственное место,
        где они туда попадают (спецификация дня 11, §5.4).

        Сразу после первого сообщения (системного промпта): долговременная,
        потом рабочая — от самого устойчивого к самому изменчивому (§3.5),
        каждый блок только если слой в запросе и блок не пуст. Память
        стратегии и хвост истории идут дальше как были: ведущие
        `system`-сообщения стратегии оказываются сразу после блоков слоёв.
        """
        if self._memory is None or not messages:
            return messages
        blocks: list[dict] = []
        if memory.LAYER_LONG_TERM in self._request_layers:
            block = memory.long_term_block(long_term, self._memory.slots)
            if block is not None:
                blocks.append(block)
        if memory.LAYER_WORKING in self._request_layers:
            block = self._memory.working_block()
            if block is not None:
                blocks.append(block)
        if not blocks:
            return messages
        return messages[:1] + blocks + messages[1:]

    def _with_profile(
        self,
        messages: list[dict],
        profile: "user_profile.UserProfile | None",
        mode_choice: "user_profile.ModeChoice | None",
    ) -> list[dict]:
        """Блок профиля в готовом списке сообщений — единственное место, где
        он туда попадает (спецификация дня 12, §5.4). Уходит только если
        `ModeChoice.sent` и блок не пуст; вставляется сразу после системного
        промпта — стратегии и модель памяти о профиле не знают."""
        if (
            profile is None
            or mode_choice is None
            or not mode_choice.sent
            or not messages
        ):
            return messages
        block = user_profile.profile_block(profile, mode_choice.mode)
        if block is None:
            return messages
        return messages[:1] + [block] + messages[1:]

    def _long_term_entries(self) -> dict:
        """Снимок записей долговременной памяти — копия словаря из памяти
        процесса (файл хранилище читает один раз, при создании); `{}` —
        долговременная память не подключена."""
        if self._long_term is None:
            return {}
        return self._long_term.entries()

    def _profile_snapshot(self) -> "user_profile.UserProfile | None":
        """Профиль этого хода — разобранный снимок хранилища профиля (день
        12, §5.1): чистая функция на словаре в пару килобайт, без кэша.
        `None` — у агента нет профиля, он ведёт себя как на дне 11.
        Замечания разбора здесь не логируются — их один раз при старте
        логирует `app.py`."""
        if self._profile is None:
            return None
        parsed, _ = user_profile.parse_profile(self._profile.current())
        return parsed

    def _preview_mode_choice(
        self, profile: "user_profile.UserProfile | None"
    ) -> "user_profile.ModeChoice":
        """Что уйдёт в запрос без вызова роутера (день 12, §5.1, §4.4): у
        панели и у сборки без нового хода нет причины звать модель. Профиля
        нет — режима нет; профиль есть, а роутера нет (REPL) — `авто`
        ведёт себя как «первый режим профиля»."""
        if profile is None:
            return user_profile.ModeChoice(False, None, "у агента нет профиля")
        if self._router is None:
            if profile.modes:
                return user_profile.ModeChoice(
                    True, profile.modes[0].name, "роутера у агента нет"
                )
            return user_profile.ModeChoice(True, None, "в профиле нет режимов")
        return self._router.preview(profile)

    def _context_view(
        self,
        question: str = "",
        long_term: dict | None = None,
        profile: "user_profile.UserProfile | None" = None,
        mode_choice: "user_profile.ModeChoice | None" = None,
        always: list[dict] | None = None,
        tools_json: str | None = None,
    ) -> tuple[list[dict], ContextView]:
        """Сборка запроса и всё, что про неё нужно знать панели и логам, —
        одним проходом.

        Отдаёт и сам список сообщений, и `ContextView`: `ask()` нужно и то и
        другое, и собирать запрос дважды (один раз чтобы отправить, другой
        чтобы показать) — верный способ разъехаться.

        Чистый метод: `describe()`, `prepare()` и `build()` ничего не меняют и
        в сеть не ходят, поэтому его безопасно звать на каждый рендер панели.
        `long_term` — снимок долговременной памяти (день 11): `ask()` передаёт
        снимок этого хода, панель — `None`, и тогда берётся свежий. `profile`
        и `mode_choice` (день 12) — тем же приёмом: `ask()` передаёт снимок и
        решение этого хода, панель — `None`, и тогда берётся превью без
        вызова роутера. `always` (день 14) — снимок постоянных инвариантов, тем
        же приёмом. `tools_json` (день 17) — схемы инструментов этого хода
        строкой JSON (`""` — инструментов в запросе нет); `None` — панель, и
        тогда берутся схемы последнего полученного каталога (§5.4).
        """
        if long_term is None:
            long_term = self._long_term_entries()
        if profile is None:
            profile = self._profile_snapshot()
        if mode_choice is None:
            mode_choice = self._preview_mode_choice(profile)
        if always is None:
            always = self._invariant_snapshot()
        if tools_json is None:
            tools_json = self._preview_tools_json()
        messages = self._build_messages(
            question, long_term, profile, mode_choice, always
        )
        usage = tokens.context_usage(
            self._count_messages(messages, tools_json),
            model=self._config.model,
            max_tokens=self._config.max_tokens,
            calibration=self.calibration,
        )
        # База для сравнения: во сколько обошёлся бы тот же ход без всякого
        # управления контекстом. Считается тем же счётчиком по той же сборке,
        # только стратегией «Вся история». С дня 11 — с теми же слоями памяти,
        # с дня 12 — с тем же профилем, с дня 13 — с тем же блоком задачи:
        # экономия говорит только о стратегии, а не о том, что слои, профиль
        # или задача добавили.
        # С дня 14 — с тем же блоком инвариантов, с дня 17 — с теми же
        # схемами инструментов.
        full = self._count_messages(
            self._with_invariants(
                self._with_profile(
                    self._with_layers(
                        self._with_task(
                            _FULL_HISTORY.build(
                                self._config.system_prompt, self._messages,
                                question,
                            )
                        ),
                        long_term,
                    ),
                    profile, mode_choice,
                ),
                always,
            ),
            tools_json,
        )
        state = self.strategy.describe(self._messages)
        task = self.strategy.prepare(self._messages, question)
        return messages, ContextView(
            strategy=self._strategy_name,
            state=state,
            usage=usage,
            full=full,
            # Сколько сообщений истории реально ушло в запрос: `per_message`
            # считается только по ним, память стратегии в этот ряд не входит.
            sent_messages=len(usage.request.per_message),
            history_messages=len(self._messages),
            # Экономия — по сырым оценкам обеих сборок: калибровка это общий
            # множитель, в отношении он бы сократился.
            saved_tokens=full.total - usage.estimated,
            # В панель уходит описание назревшей задачи, а не она сама: её
            # `messages` могут весить сотни килобайт.
            pending_label=task.label if task else "",
            pending_messages=task.covers - state.covered if task else 0,
            pending_sent_messages=task.sends if task else 0,
        )

    def _run_context_task(
        self, client: OpenAI, question: str
    ) -> ServiceCall | None:
        """Служебный вызов, если стратегия его попросила: обновление памяти —
        свёртка в сводку или разбор фактов, в зависимости от активной
        стратегии (день 10). Метод один на обе: слова для лога и панели
        приходят от стратегии (`task.label`, `StrategyState.memory_label`,
        `StrategyState.last_update`) — агент не знает, сводка это или факты.

        Сам вызов модели делает `_call_service_model()` (день 11): через него
        же идёт разбор памяти. Поведение, логи и `ServiceCall` стратегии от
        этого не изменились.

        Это настоящий вызов, но не ход: в стек сообщений он не пишет, строку
        журнала ходов не создаёт и `_last_reply` не трогает.
        """
        task = self.strategy.prepare(self._messages, question)
        if task is None:
            return None

        before = self.strategy.describe(self._messages)
        covered_before = before.covered
        folded = self._messages[covered_before:task.covers]
        folded_tokens = sum(
            tokens.estimate_tokens(message.get("content")) for message in folded
        )

        started = time.perf_counter()
        try:
            result = self._call_service_model(client, task.messages, task.max_tokens)
        except Exception as exc:
            logger.exception("[%s] служебный вызов упал", self._log_name)
            call = ServiceCall(
                kind=task.kind, label=task.label, ok=False,
                # В `error` только причина, без слова «свёртка»: и лог, и
                # панель подписывают её сами, и дважды это читается плохо.
                error=str(exc),
                elapsed=time.perf_counter() - started,
                prompt_tokens=None, completion_tokens=None, total_tokens=None,
                cost_usd=None, covers=0, folded_tokens=folded_tokens, text="",
                memory_label=before.memory_label,
            )
            self._record_service(call)
            # Сколько сообщений уйдёт в запрос, здесь не пишется: у фактов
            # хвост не короче окна, и число неучтённых разошлось бы со
            # строкой стратегии, которая идёт в лог следом.
            logger.warning(
                "[%s] служебный вызов — %s: не удался (%s); ход не "
                "отменяется: память не сдвинулась, в запрос уйдёт всё "
                "неучтённое, вызов повторится на следующем ходе",
                self._log_name, task.label, call.error,
            )
            return call

        text = result.text
        if not text:
            call = ServiceCall(
                kind=task.kind, label=task.label, ok=False,
                error="модель вернула пустой ответ",
                elapsed=result.elapsed,
                prompt_tokens=result.prompt_tokens,
                completion_tokens=result.completion_tokens,
                total_tokens=result.total_tokens, cost_usd=result.cost_usd,
                covers=0, folded_tokens=folded_tokens, text="",
                finish_reason=result.finish_reason,
                memory_label=before.memory_label,
            )
            self._record_service(call)
            logger.warning(
                "[%s] служебный вызов — %s: модель вернула пустой ответ — "
                "память не сдвинулась, сообщения #%d-#%d останутся в запросе "
                "целиком, вызов повторится на следующем ходе",
                self._log_name, task.label, covered_before, task.covers - 1,
            )
            return call

        # `apply()` — единственный, кто знает, разобралась ли хоть одна
        # строка (день 10, §5.1): непустой ответ ещё не значит успех.
        applied = self.strategy.apply(task, text)
        after = self.strategy.describe(self._messages)
        call = ServiceCall(
            kind=task.kind,
            label=task.label,
            ok=applied,
            error=None if applied else "ответ модели не разобран",
            elapsed=result.elapsed,
            prompt_tokens=result.prompt_tokens,
            completion_tokens=result.completion_tokens,
            total_tokens=result.total_tokens,
            cost_usd=result.cost_usd,
            covers=task.covers - covered_before if applied else 0,
            folded_tokens=folded_tokens,
            text=text,
            finish_reason=result.finish_reason,
            memory_label=after.memory_label,
            memory_update=after.last_update if applied else "",
        )
        # Токены потрачены в любом случае — считаем их до того, как решим,
        # годится ли результат.
        self._record_service(call)
        if not applied:
            logger.warning(
                "[%s] служебный вызов — %s: ответ модели не разобран — "
                "память не сдвинулась, начало ответа: %r; в запрос уйдёт "
                "всё неучтённое, вызов повторится на следующем ходе",
                self._log_name, task.label, text[:200],
            )
            return call

        # Немедленное сохранение: обновление уже оплачено, и падение до
        # основного вызова не должно его терять.
        self._persist()
        logger.info(
            "[%s] служебный вызов — %s: учтено ≈%s токенов истории → %s "
            "≈%s токенов (%s); %.2fs, tokens=%s/%s/%s, cost=%s",
            self._log_name, task.label, _num(folded_tokens),
            after.memory_label.lower(),
            _num(tokens.estimate_tokens(after.memory_text)),
            after.last_update, result.elapsed,
            result.prompt_tokens, result.completion_tokens, result.total_tokens,
            _cost_str(result.cost_usd),
        )
        # Обрезанный ответ применён — отказ от него оставил бы задачу
        # назревшей, и она повторялась бы каждый ход за деньги и с тем же
        # итогом. Но молча это не проходит: штатно в потолок упираться нельзя.
        if result.finish_reason == "length":
            logger.warning(
                "[%s] служебный вызов — %s: ответ упёрся в max_tokens=%s и "
                "оборван на полуслове — применён как есть; если это "
                "повторяется, потолок мал для реальной длины (спецификации "
                "дня 9, §3.1, и дня 10, §3.1)",
                self._log_name, task.label, task.max_tokens,
            )
        return call

    def _call_service_model(
        self, client: OpenAI, messages: list[dict], max_tokens: int | None
    ) -> _ServiceResponse:
        """Служебный вызов модели — второе (и последнее) место в проекте, где
        вызывается `chat.completions.create` (спецификация дня 11, §5.3). Через
        него идут обе служебные работы: вызов стратегии и разбор памяти.

        Набор параметров у него намеренно другой, чем у основного вызова
        (день 9): сообщения из задачи, `thinking` всегда выключен (скрытые
        reasoning-токены тратят тот же бюджет `max_tokens`, что и видимый
        ответ, и на маленьком лимите ответ пришёл бы пустым), `max_tokens` из
        задачи, ни температуры, ни `stop`. Модель — из конфига агента:
        отдельной модели под служебные работы нет (правило дня 9).

        Исключение API пробрасывается вызывающему: что сбой значит для
        памяти, знает работа вокруг вызова, а не вызов.
        """
        started = time.perf_counter()
        response = client.chat.completions.create(
            model=self._config.model,
            messages=messages,
            extra_body={"thinking": {"type": "disabled"}},
            **({"max_tokens": max_tokens} if max_tokens else {}),
        )
        elapsed = time.perf_counter() - started
        choice = response.choices[0]
        usage = response.usage
        prompt_tokens = getattr(usage, "prompt_tokens", None)
        completion_tokens = getattr(usage, "completion_tokens", None)
        return _ServiceResponse(
            text=(choice.message.content or "").strip(),
            finish_reason=choice.finish_reason,
            prompt_tokens=prompt_tokens,
            completion_tokens=completion_tokens,
            total_tokens=getattr(usage, "total_tokens", None),
            cost_usd=estimate_cost_usd(
                self._config.model, prompt_tokens, completion_tokens
            ),
            elapsed=elapsed,
        )

    def _run_invariant_guard(
        self, client: OpenAI, question: str, always: list[dict]
    ) -> tuple["invariants.Conflict | None", ServiceCall | None]:
        """Страж инвариантов перед ответом (спецификация дня 14, §6.3):
        `prepare()` → `_call_service_model()` → `apply()`.

        Сверять нечего — `(None, None)`: нет книги, нет истории, пустая
        книга, все инварианты выключены, остались только инварианты над
        переходами, вопрос пустой (`InvariantBook.prepare()` сам это решает).
        Страж только называет конфликт нового сообщения с инвариантами: ход не
        отменяется и ничего не блокируется — отказывает ассистент, а код
        только показывает конфликт (§2.5).

        Сбой хода не отменяет (правило дня 9 для служебного вызова):
        исключение API, пустой и неразобранный ответ оставляют последний
        конфликт как был. **Обрезанный потолком ответ применяется** с
        предупреждением в логе и пометкой в панели — в отличие от трекера
        (§2.4 дня 13): вердикт стоит первой строкой и разбирается даже у
        оборванного ответа, а потерянный номер ограничения лишь сузит строку
        конфликта. Номера вне списка стража отклоняются и видны в логе.
        """
        if self._invariants is None or not self._config.keep_history:
            return None, None
        task = self._invariants.prepare(always, self._messages, question)
        if task is None:
            return None, None

        started = time.perf_counter()
        try:
            result = self._call_service_model(client, task.messages, task.max_tokens)
        except Exception as exc:
            logger.exception("[%s] страж инвариантов упал", self._log_name)
            call = ServiceCall(
                kind="invariant", label=task.label, ok=False, error=str(exc),
                elapsed=time.perf_counter() - started,
                prompt_tokens=None, completion_tokens=None, total_tokens=None,
                cost_usd=None, covers=0, folded_tokens=0, text="",
                memory_label=invariants.GUARD_CALL_LABEL,
            )
            self._record_guard(call)
            logger.warning(
                "[%s] страж инвариантов — %s: не удался (%s); ход не "
                "отменяется — последний конфликт не тронут, основной вызов "
                "идёт без проверки этого сообщения",
                self._log_name, task.label, call.error,
            )
            return None, call

        text = result.text
        if not text:
            call = ServiceCall(
                kind="invariant", label=task.label, ok=False,
                error="модель вернула пустой ответ",
                elapsed=result.elapsed,
                prompt_tokens=result.prompt_tokens,
                completion_tokens=result.completion_tokens,
                total_tokens=result.total_tokens, cost_usd=result.cost_usd,
                covers=0, folded_tokens=0, text="",
                finish_reason=result.finish_reason,
                memory_label=invariants.GUARD_CALL_LABEL,
            )
            self._record_guard(call)
            logger.warning(
                "[%s] страж инвариантов — %s: модель вернула пустой ответ "
                "(finish_reason=%s) — последний конфликт не тронут",
                self._log_name, task.label, result.finish_reason,
            )
            return None, call

        conflict, parsed = self._invariants.apply(
            task, text, always, self._messages, _now_iso()
        )
        truncated = result.finish_reason == "length"
        if not parsed:
            error = "ответ стража не разобран"
        elif truncated:
            error = "ответ оборван потолком, применён как есть"
        else:
            error = None
        update = self._invariants.last_update
        call = ServiceCall(
            kind="invariant",
            label=task.label,
            ok=parsed,
            error=error,
            elapsed=result.elapsed,
            prompt_tokens=result.prompt_tokens,
            completion_tokens=result.completion_tokens,
            total_tokens=result.total_tokens,
            cost_usd=result.cost_usd,
            covers=0,
            folded_tokens=0,
            text=text,
            finish_reason=result.finish_reason,
            memory_label=invariants.GUARD_CALL_LABEL,
            memory_update=update if parsed else "",
        )
        self._record_guard(call)
        if not parsed:
            logger.warning(
                "[%s] страж инвариантов — %s: ответ не разобран (начало: %r) "
                "— последний конфликт не тронут",
                self._log_name, task.label, text[:200],
            )
            return None, call

        numbers = (
            f"; книга: {self._book_count_str(always)}" if conflict is None else ""
        )
        logger.info(
            "[%s] страж инвариантов: %s → %s%s; finish_reason=%s %.2fs, "
            "tokens=%s/%s/%s, cost=%s; ответ: %r",
            self._log_name, task.label, update, numbers, result.finish_reason,
            result.elapsed, _num(result.prompt_tokens),
            _num(result.completion_tokens), _num(result.total_tokens),
            _cost_str(result.cost_usd), text,
        )
        if conflict is not None and conflict.unknown:
            # `info`, а не `warning`: это решение книги, а не сбой вызова.
            logger.info(
                "[%s] страж инвариантов: назван конфликт с «%s» — такого "
                "инварианта в списке стража нет, эти номера отклонены",
                self._log_name, "», «".join(conflict.unknown),
            )
        if truncated:
            logger.warning(
                "[%s] страж инвариантов — %s: ответ упёрся в max_tokens=%s и "
                "оборван на полуслове — применён как есть; если это "
                "повторяется, потолок мал (спецификация дня 14, §3.5)",
                self._log_name, task.label, task.max_tokens,
            )
        return conflict, call

    def _book_count_str(self, always: list[dict]) -> str:
        """«4 инварианта в книге (3 действуют)» — для строки лога стража."""
        view = self._invariants.describe(always, self._messages)
        return (
            f"{len(view.items)} {_invariants_word(len(view.items))} в книге "
            f"({view.active} действуют)"
        )

    def _run_memory_task(
        self, client: OpenAI, question: str, long_term: dict
    ) -> ServiceCall | None:
        """Разбор памяти перед ответом (спецификация дня 11, §5.3):
        `prepare()` → вызов → `apply()`.

        Модель раскладывает сказанное игроком по ключам карты: рабочие ключи
        сразу сливаются в рабочую память, долговременные становятся
        кандидатами — в долговременную память без решения человека ничего не
        попадает. `long_term` — снимок записей долговременной памяти этого
        хода; во вход разбора уходят только значения долговременной части
        карты.

        Сбой хода не отменяет — правило дня 9 для служебного вызова целиком:
        исключение API, пустой или неразобранный ответ оставляют рабочую
        память, кандидатов и `covered` как были, разбор повторится на
        следующем ходе с накопившимся хвостом. Обрезанный потолком ответ
        применяется с предупреждением. Это настоящий вызов, но не ход, и не
        `service_*`: разбор ничего не экономит.
        """
        if self._memory is None or not self._config.keep_history:
            return None
        values = memory.long_term_values(long_term, self._memory.slots)
        task = self._memory.prepare(self._messages, question, values)
        if task is None:
            return None

        before = self._memory.describe(self._messages)
        folded = self._messages[before.covered:task.covers]
        folded_tokens = sum(
            tokens.estimate_tokens(message.get("content")) for message in folded
        )

        started = time.perf_counter()
        try:
            result = self._call_service_model(client, task.messages, task.max_tokens)
        except Exception as exc:
            logger.exception("[%s] разбор памяти упал", self._log_name)
            call = ServiceCall(
                kind="memory", label=task.label, ok=False, error=str(exc),
                elapsed=time.perf_counter() - started,
                prompt_tokens=None, completion_tokens=None, total_tokens=None,
                cost_usd=None, covers=0, folded_tokens=folded_tokens, text="",
                memory_label=MEMORY_CALL_LABEL,
            )
            self._record_memory(call)
            logger.warning(
                "[%s] %s: не удался (%s); ход не отменяется: рабочая память и "
                "кандидаты не сдвинулись, разбор повторится на следующем ходе "
                "с накопившимся хвостом",
                self._log_name, task.label, call.error,
            )
            return call

        text = result.text
        if not text:
            call = ServiceCall(
                kind="memory", label=task.label, ok=False,
                error="модель вернула пустой ответ",
                elapsed=result.elapsed,
                prompt_tokens=result.prompt_tokens,
                completion_tokens=result.completion_tokens,
                total_tokens=result.total_tokens, cost_usd=result.cost_usd,
                covers=0, folded_tokens=folded_tokens, text="",
                finish_reason=result.finish_reason,
                memory_label=MEMORY_CALL_LABEL,
            )
            self._record_memory(call)
            logger.warning(
                "[%s] %s: модель вернула пустой ответ (finish_reason=%s) — "
                "рабочая память и кандидаты не сдвинулись, разбор повторится "
                "на следующем ходе",
                self._log_name, task.label, result.finish_reason,
            )
            return call

        applied = self._memory.apply(task, text, values)
        after = self._memory.describe(self._messages)
        call = ServiceCall(
            kind="memory",
            label=task.label,
            ok=applied,
            error=None if applied else "ответ модели не разобран",
            elapsed=result.elapsed,
            prompt_tokens=result.prompt_tokens,
            completion_tokens=result.completion_tokens,
            total_tokens=result.total_tokens,
            cost_usd=result.cost_usd,
            covers=task.covers - before.covered if applied else 0,
            folded_tokens=folded_tokens,
            text=text,
            finish_reason=result.finish_reason,
            memory_label=MEMORY_CALL_LABEL,
            memory_update=after.last_update if applied else "",
        )
        # Токены потрачены в любом случае — считаем их до того, как решим,
        # годится ли результат.
        self._record_memory(call)
        if not applied:
            logger.warning(
                "[%s] %s: ответ модели не разобран — рабочая память и "
                "кандидаты не сдвинулись, начало ответа: %r; разбор повторится "
                "на следующем ходе",
                self._log_name, task.label, text[:200],
            )
            return call

        # Немедленное сохранение: рабочая память и покрытие уже оплачены, и
        # падение основного вызова не должно их терять.
        self._persist()
        # Ответ разбора — одна-три строки, и в логе он целиком: по нему видно,
        # «нет изменений» это было или повтор того, что уже лежит в памяти.
        logger.info(
            "[%s] %s: %s; finish_reason=%s %.2fs, tokens=%s/%s/%s, cost=%s; "
            "ответ: %r",
            self._log_name, task.label, after.last_update, result.finish_reason,
            result.elapsed, _num(result.prompt_tokens),
            _num(result.completion_tokens), _num(result.total_tokens),
            _cost_str(result.cost_usd), text,
        )
        waiting_before = {candidate.key: candidate for candidate in before.candidates}
        for candidate in after.candidates:
            if waiting_before.get(candidate.key) != candidate:
                logger.info(
                    "[%s] кандидат в долговременную память: %s — ждёт решения",
                    self._log_name, _candidate_str(candidate),
                )
        if after.rejected:
            # `info`, а не `warning`: это решение карты памяти, а не сбой.
            logger.info(
                "[%s] %s: ключи вне карты отклонены — %s; в память не попали",
                self._log_name, task.label, ", ".join(after.rejected),
            )
        if result.finish_reason == "length":
            logger.warning(
                "[%s] %s: ответ упёрся в max_tokens=%s и оборван на полуслове — "
                "применён как есть; если это повторяется, потолок мал "
                "(спецификация дня 11, §3.2)",
                self._log_name, task.label, task.max_tokens,
            )
        return call

    def _run_route_task(
        self,
        client: OpenAI,
        question: str,
        profile: "user_profile.UserProfile | None",
    ) -> tuple["user_profile.ModeChoice", ServiceCall | None]:
        """Выбор режима профиля на этот ход (спецификация дня 12, §5.2,
        §5.3): `prepare()` → `_call_service_model()` → `settle()`.

        Нет профиля у агента — режима нет, роутер не вызывается. Есть
        профиль, но нет роутера (REPL, §5.1) — `авто` ведёт себя как
        «первый режим профиля», без служебного вызова. Сбой хода не
        отменяет (правило дня 9 для служебного вызова): исключение API,
        пустой или неразобранный ответ дают запасной режим — режим прошлого
        хода, если он ещё есть в профиле, иначе первый; сам вызов всё равно
        оплачен и посчитан.
        """
        if profile is None or self._router is None:
            return self._preview_mode_choice(profile), None

        self._warn_stale_profile_choice(profile)
        task = self._router.prepare(profile, self._messages, question)
        if task is None:
            choice, _ = self._router.settle(profile, None, None)
            return choice, None

        started = time.perf_counter()
        try:
            result = self._call_service_model(client, task.messages, task.max_tokens)
        except Exception as exc:
            logger.exception("[%s] роутер профиля упал", self._log_name)
            choice, _ = self._router.settle(profile, task, None)
            call = ServiceCall(
                kind="route", label=task.label, ok=False, error=str(exc),
                elapsed=time.perf_counter() - started,
                prompt_tokens=None, completion_tokens=None, total_tokens=None,
                cost_usd=None, covers=0, folded_tokens=0, text="",
                memory_label=ROUTE_CALL_LABEL,
                memory_update=_route_update(choice),
            )
            self._record_route(call)
            logger.warning(
                "[%s] роутер профиля — %s: не удался (%s); ход не "
                "отменяется — режим этого хода: %s",
                self._log_name, task.label, call.error, _route_update(choice),
            )
            return choice, call

        text = result.text
        choice, ok = self._router.settle(profile, task, text or None)
        call = ServiceCall(
            kind="route",
            label=task.label,
            ok=ok,
            error=None if ok else "ответ роутера не разобран",
            elapsed=result.elapsed,
            prompt_tokens=result.prompt_tokens,
            completion_tokens=result.completion_tokens,
            total_tokens=result.total_tokens,
            cost_usd=result.cost_usd,
            covers=0,
            folded_tokens=0,
            text=text,
            finish_reason=result.finish_reason,
            memory_label=ROUTE_CALL_LABEL,
            memory_update=_route_update(choice),
        )
        self._record_route(call)
        if not ok:
            logger.warning(
                "[%s] роутер профиля — %s: ответ не разобран (начало: %r) — "
                "режим этого хода: %s",
                self._log_name, task.label, text[:200], _route_update(choice),
            )
        else:
            logger.info(
                "[%s] роутер профиля: %s → %s; finish_reason=%s %.2fs, "
                "tokens=%s/%s/%s, cost=%s; ответ: %r",
                self._log_name, task.label, _route_update(choice),
                result.finish_reason, result.elapsed,
                _num(result.prompt_tokens), _num(result.completion_tokens),
                _num(result.total_tokens), _cost_str(result.cost_usd), text,
            )
        if result.finish_reason == "length":
            logger.warning(
                "[%s] роутер профиля — %s: ответ упёрся в max_tokens=%s и "
                "оборван на полуслове; если это повторяется, потолок мал "
                "(спецификация дня 12, §3.3)",
                self._log_name, task.label, task.max_tokens,
            )
        return choice, call

    def _log_task_outcome(self, outcome: "task_state.Outcome", source: str) -> None:
        """Строка лога про исход события задачи (день 13, день 15 §5): отказ с
        причиной и источником, откаты назад по графу — своей строкой с путём к
        файлу, всё остальное — словами исхода. Один код на кнопку человека и
        на трекер: формулировки в логе не разъезжаются."""
        state = self._task.state if self._task is not None else None
        if outcome.rejection is not None:
            tail = ""
            if source == task_state.SOURCE_TRACKER and state is not None:
                tail = (
                    f"; состояние не изменилось — {state.stage}"
                    f"{' (на паузе)' if state.paused else ''}"
                )
            logger.info(
                "[%s] задача: отклонено «%s» (%s): %s%s",
                self._log_name, outcome.rejection.event,
                outcome.rejection.source, outcome.rejection.reason, tail,
            )
            return
        if not outcome.changed:
            return
        where = f"sessions/{self._session_id}.json"
        if outcome.event == task_state.EVENT_BACK_TO_PLAN and state is not None:
            logger.info(
                "[%s] задача: возврат к плану (%s) → %s; итоги шагов стёрты, "
                "план из %d шагов остался черновиком → %s",
                self._log_name, source, state.stage, len(state.steps), where,
            )
        elif outcome.event == task_state.EVENT_REOPEN and state is not None:
            logger.info(
                "[%s] задача: переоткрыта пользователем → проверка %d из %d → %s",
                self._log_name, state.step, len(state.checks), where,
            )
        elif source == task_state.SOURCE_HUMAN:
            # Переход трекера описывает строка самого трекера ниже.
            logger.info("[%s] задача: %s", self._log_name, outcome.note)

    def _run_task_tracker(
        self, client: OpenAI, question: str, always: list[dict] | None = None
    ) -> tuple["task_state.Outcome | None", ServiceCall | None]:
        """Трекер задачи перед ответом (спецификация дня 13, §5.3):
        `prepare()` → `_call_service_model()` → `apply()`.

        Задачи для трекера нет — `(None, None)`: нет автомата, нет истории,
        задача не на активном этапе, вопрос пустой, ход «Начать задачу» или
        повтор на месте истории, где переход трекера уже применён
        (`task_state.TaskMachine.prepare()` сам это решает).

        Сбой хода не отменяет (правило дня 9 для служебного вызова):
        исключение API, пустой ответ и ответ, оборванный потолком, состояние
        не трогают. **Обрезанный ответ здесь не применяется** — в отличие от
        сводки, фактов и разбора памяти: оборванный ответ трекера — это
        оборванный план, а утверждённый план с потерянными шагами пользователь
        не заметит до этапа проверки (§2.4).

        С дня 14 (§6.4) автомату уходят ограничения переходов, собранные из
        инвариантов (`_transition_guards()`): переход трекера под ограничением
        «с подтверждением» не применяется, а становится ожиданием — состояние
        не менялось, отказа нет, ждёт кнопки «Подтвердить переход». `always` —
        снимок постоянных инвариантов этого хода; `None` — взять свежий.
        """
        if self._task is None or not self._config.keep_history:
            return None, None
        task = self._task.prepare(self._messages, question)
        if task is None:
            return None, None

        started = time.perf_counter()
        try:
            result = self._call_service_model(client, task.messages, task.max_tokens)
        except Exception as exc:
            logger.exception("[%s] трекер задачи упал", self._log_name)
            call = ServiceCall(
                kind="task", label=task.label, ok=False, error=str(exc),
                elapsed=time.perf_counter() - started,
                prompt_tokens=None, completion_tokens=None, total_tokens=None,
                cost_usd=None, covers=0, folded_tokens=0, text="",
                memory_label=task_state.TASK_CALL_LABEL,
            )
            self._record_task_tracker(call)
            logger.warning(
                "[%s] трекер задачи — %s: не удался (%s); ход не "
                "отменяется — состояние задачи не тронуто",
                self._log_name, task.label, call.error,
            )
            return None, call

        text = result.text
        if not text:
            call = ServiceCall(
                kind="task", label=task.label, ok=False,
                error="модель вернула пустой ответ",
                elapsed=result.elapsed,
                prompt_tokens=result.prompt_tokens,
                completion_tokens=result.completion_tokens,
                total_tokens=result.total_tokens, cost_usd=result.cost_usd,
                covers=0, folded_tokens=0, text="",
                finish_reason=result.finish_reason,
                memory_label=task_state.TASK_CALL_LABEL,
            )
            self._record_task_tracker(call)
            logger.warning(
                "[%s] трекер задачи — %s: модель вернула пустой ответ — "
                "состояние задачи не тронуто",
                self._log_name, task.label,
            )
            return None, call

        if result.finish_reason == "length":
            call = ServiceCall(
                kind="task", label=task.label, ok=False,
                error="ответ упёрся в потолок и оборван — не применён",
                elapsed=result.elapsed,
                prompt_tokens=result.prompt_tokens,
                completion_tokens=result.completion_tokens,
                total_tokens=result.total_tokens, cost_usd=result.cost_usd,
                covers=0, folded_tokens=0, text=text,
                finish_reason=result.finish_reason,
                memory_label=task_state.TASK_CALL_LABEL,
            )
            self._record_task_tracker(call)
            logger.warning(
                "[%s] трекер задачи — %s: ответ упёрся в max_tokens=%s и "
                "оборван на полуслове — НЕ применён (оборванный план хуже "
                "отсутствия перехода); состояние задачи не тронуто",
                self._log_name, task.label, task.max_tokens,
            )
            return None, call

        if always is None:
            always = self._invariant_snapshot()
        outcome, parsed = self._task.apply(
            task, text, self._messages, _now_iso(),
            self._transition_guards(always),
        )
        call = ServiceCall(
            kind="task",
            label=task.label,
            ok=parsed,
            error=None if parsed else "ответ трекера не разобран",
            elapsed=result.elapsed,
            prompt_tokens=result.prompt_tokens,
            completion_tokens=result.completion_tokens,
            total_tokens=result.total_tokens,
            cost_usd=result.cost_usd,
            covers=0,
            folded_tokens=0,
            text=text,
            finish_reason=result.finish_reason,
            memory_label=task_state.TASK_CALL_LABEL,
            memory_update=outcome.note if parsed else "",
        )
        self._record_task_tracker(call)
        # Переход сохраняется сразу, как разбор памяти: падение основного
        # вызова не должно его терять (§2.6). Отказ и «событий нет» состояние
        # не меняют — сохранять нечего.
        if outcome.changed:
            self._persist()
        if outcome.pending is not None:
            logger.info(
                "[%s] задача: «%s» ждёт подтверждения пользователя (%s) — "
                "состояние не изменилось: %s",
                self._log_name, outcome.pending.event,
                outcome.pending.source_note,
                self._task.describe(self._messages).step_text,
            )
        else:
            self._log_task_outcome(outcome, task_state.SOURCE_TRACKER)
        if outcome.off_route is not None:
            in_request = (
                "строка уйдёт в блок запроса"
                if self._task_in_request
                else "блок в запрос не уходит — переключатель выключен"
            )
            logger.info(
                "[%s] задача: сход с маршрута (%s) — «%s»; состояние не "
                "тронуто, %s",
                self._log_name, outcome.off_route.kind,
                outcome.off_route.why or "фраза не названа", in_request,
            )
        if outcome.rejection is not None or outcome.off_route is not None:
            # Раз в ход, когда он был: не каждым ходом (день 15, §5).
            logger.info(
                "[%s] задача: красный путь этой сессии — отклонено "
                "переходов: %d, сходов с маршрута: %d",
                self._log_name, self._task.rejected_total,
                self._task.off_route_total,
            )
        if not parsed:
            logger.warning(
                "[%s] трекер задачи — %s: ответ не разобран (начало: %r) — "
                "состояние задачи не тронуто",
                self._log_name, task.label, text[:200],
            )
        else:
            logger.info(
                "[%s] трекер задачи — %s → %s; finish_reason=%s %.2fs, "
                "tokens=%s/%s/%s, cost=%s; ответ: %r",
                self._log_name, task.label, outcome.note, result.finish_reason,
                result.elapsed, _num(result.prompt_tokens),
                _num(result.completion_tokens), _num(result.total_tokens),
                _cost_str(result.cost_usd), text,
            )
        return outcome, call

    def _warn_stale_profile_choice(self, profile: "user_profile.UserProfile") -> None:
        """Устаревшее название режима в переключателе «Профиль в запросе»
        (день 12, §5.9): режима с таким именем в профиле больше нет.
        Логируется на `info` — это решение человека или правки профиля, а не
        сбой; ведёт себя как `CHOICE_AUTO` (§4.4)."""
        choice = self._router.choice
        if choice in (user_profile.CHOICE_AUTO, user_profile.CHOICE_OFF):
            return
        if user_profile.mode_by_name(profile, choice) is None:
            logger.info(
                "[%s] переключатель «Профиль в запросе» указывает на «%s», "
                "которого больше нет в профиле — работаем как «%s»",
                self._log_name, choice, user_profile.CHOICE_AUTO,
            )

    def _count_messages(
        self, messages: list[dict], tools_json: str = ""
    ) -> tokens.RequestTokens:
        """Разложение готового списка сообщений на систему / долговременную и
        рабочую память / память стратегии / историю / вопрос.

        Единственное место, где список сообщений превращается в оценку: и
        `ask()`, и `context_usage()` ходят сюда, поэтому «сколько посчитали»
        и «сколько отправили» считаются одним и тем же способом по одному и
        тому же списку.

        С дня 9 разбор идёт по ролям, а не по позициям: первое сообщение —
        системный промпт, последнее — вопрос, а все `system` между ними это
        память стратегии (сводка сегодня, блок фактов у дня 10). Правило
        безопасно: история агента нормализуется до `user`/`assistant` ещё с
        дня 6, и `system` в ней не бывает.

        С дня 11 (§5.6) среди этих `system` отделяются блоки слоёв: то, что
        начинается с `memory.LONG_TERM_HEADER`, — корзина `long_term`, с
        `memory.WORKING_HEADER` — `working`, остальное — память стратегии.
        Правило безопасно по той же причине: `system`-сообщения в запросе
        ставит только код проекта, и заголовки — его константы.

        С дня 12 (§5.6) так же отделяется блок профиля: то, что начинается с
        `user_profile.PROFILE_HEADER`, — корзина `profile`; корзина `memory`
        (память стратегии) — то, что не начинается ни с одного из четырёх
        заголовков.

        С дня 13 (§5.7) так же отделяется блок состояния задачи: то, что
        начинается с `task_state.TASK_HEADER`, — корзина `task`.

        С дня 14 (§7.2) так же отделяется блок инвариантов: то, что начинается
        с `invariants.INVARIANT_HEADER`, — корзина `invariants`; корзина
        `memory` (память стратегии) — то, что не начинается ни с одного из
        пяти заголовков.

        С дня 17 (§5.4) сюда же приходят схемы инструментов строкой JSON —
        те же, что уходят параметром `tools`: корзина `tools`. Сообщением они
        не являются, и разбор по ролям их не касается.
        """
        middle = messages[1:-1]
        system = [
            m.get("content") or "" for m in middle if m.get("role") == "system"
        ]
        named = (
            memory.LONG_TERM_HEADER, memory.WORKING_HEADER,
            user_profile.PROFILE_HEADER, task_state.TASK_HEADER,
            invariants.INVARIANT_HEADER,
        )
        return tokens.count_request(
            system_prompt=messages[0]["content"],
            history=[m for m in middle if m.get("role") != "system"],
            question=messages[-1]["content"],
            memory="\n\n".join(text for text in system if not text.startswith(named)),
            long_term="\n\n".join(
                text for text in system if text.startswith(memory.LONG_TERM_HEADER)
            ),
            working="\n\n".join(
                text for text in system if text.startswith(memory.WORKING_HEADER)
            ),
            profile="\n\n".join(
                text for text in system if text.startswith(user_profile.PROFILE_HEADER)
            ),
            task="\n\n".join(
                text for text in system if text.startswith(task_state.TASK_HEADER)
            ),
            invariants="\n\n".join(
                text for text in system
                if text.startswith(invariants.INVARIANT_HEADER)
            ),
            tools_json=tools_json,
        )

